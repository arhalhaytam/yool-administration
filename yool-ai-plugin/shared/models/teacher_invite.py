"""TeacherInvite model — email-locked, single-use onboarding link for teachers/admins."""

import uuid
from datetime import datetime

from sqlalchemy import DateTime, ForeignKey, String, func
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy import Enum as SaEnum
from sqlalchemy.orm import Mapped, mapped_column, relationship

from .base import Base
from .user import UserRole


class TeacherInvite(Base):
    """
    One-time invite link generated by an admin to onboard a teacher or admin.

    Key properties:
    - Email-locked: only the specified email can accept the invite
    - Single-use: used_at is set on acceptance, blocking reuse
    - Role pre-assigned: the resulting account gets the role set at creation
    - Raw token never stored — only SHA-256 hash is persisted
    """

    __tablename__ = "teacher_invites"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )

    token_hash: Mapped[str] = mapped_column(String(64), unique=True, nullable=False)

    # Pre-filled email — only this address can accept the invite
    email: Mapped[str] = mapped_column(String(255), nullable=False, index=True)

    # Role that will be assigned to the resulting account
    role: Mapped[UserRole] = mapped_column(
        SaEnum(
            UserRole,
            name="user_role",
            values_callable=lambda x: [e.value for e in x],
            create_type=False,
        ),
        nullable=False,
        default=UserRole.TEACHER,
    )

    created_by: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
    )

    expires_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False
    )

    # Set when the invite is consumed
    used_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    used_by: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )

    # Relationships
    creator:      Mapped["User"]        = relationship(foreign_keys=[created_by])   # noqa: F821
    accepted_by:  Mapped["User | None"] = relationship(foreign_keys=[used_by])      # noqa: F821

    @property
    def is_pending(self) -> bool:
        from datetime import timezone
        return self.used_at is None and self.expires_at > datetime.now(timezone.utc)

    def __repr__(self) -> str:
        return f"<TeacherInvite {self.email} role={self.role} used={self.used_at is not None}>"
